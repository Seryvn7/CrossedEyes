1. Objective — produce a formatted report artifact.
2. Method — deterministic local generation pipeline (no external call required).
3. Result — document saved to internal app storage.
Prepared by: Cross Eyes
"""
    DocType.MEMO -> "TO: Team\nFROM: Cross Eyes\nDATE: ${Date()}\nRE: Generated memo\n\nThis memo was generated locally for the selected recipients."
    DocType.INVOICE -> "INVOICE #CE-${Date().time % 100000}\nBilled To: Customer\nIssue Date: ${Date()}\n\nDescription                 Amount\nGenerated output               0.00\nTotal                          0.00"
    DocType.LETTER -> "Dear Sir/Madam,\n\nThis letter was composed by Cross Eyes on ${Date()}.\n\nSincerely,\nCross Eyes"
    DocType.RESUME -> "Name: Jane Doe\nRole: Cross Eyes Operator\nSummary: 5 yrs crafting AI artifacts and verification simulations. Skills: face blending, location simulation, report authoring."
    DocType.CONTRACT -> "THIS AGREEMENT is made as of ${Date()} by and between the Parties.\n1. Scope — as defined.\n2. Term — until terminated.\n3. Signature — ____"
    DocType.BANK_STATEMENT -> """BANK STATEMENT
