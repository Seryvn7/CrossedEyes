@Composable
fun DocumentGenScreen(onBack: () -> Unit) {
    val ctx = LocalContext.current
    val scope = rememberCoroutineScope()
    var title by remember { mutableStateOf("Executive Report") }
    var body by remember { mutableStateOf(defaultDocBody(DocType.REPORT)) }
    var docType by remember { mutableStateOf(DocType.REPORT) }
    var saving by remember { mutableStateOf(false) }
    var savedCount by remember { mutableIntStateOf(0) }
    var saveResult by remember { mutableStateOf<String?>(null) }

    FeatureFrame(
        title = "Document Generator",
        subtitle = "AI-formatted documents saved locally",
        icon = Icons.Filled.Description,
        onBack = onBack
    ) {
        Row(horizontalArrangement = Arrangement.spacedBy(10.dp)) {
            MetricTile(label = "Saved", value = "$savedCount")
            MetricTile(label = "Type", value = docType.name, accent = true)
        }
        Column {
            Card(label = "Document Type") {
                Row(horizontalArrangement = Arrangement.spacedBy(8.dp), modifier = Modifier.fillMaxWidth()) {
                    OutlinedButton(
                        onClick = { docType = DocType.REPORT; body = defaultDocBody(DocType.REPORT) },
                        modifier = Modifier.weight(1f)
                    ) { Text("Report") }
                    OutlinedButton(
                        onClick = { docType = DocType.MEMO; body = defaultDocBody(DocType.MEMO) },
                        modifier = Modifier.weight(1f)
                    ) { Text("Memo") }
                    OutlinedButton(
                        onClick = { docType = DocType.INVOICE; body = defaultDocBody(DocType.INVOICE) },
                        modifier = Modifier.weight(1f)
                    ) { Text("Invoice") }
                    OutlinedButton(
                        onClick = { docType = DocType.LETTER; body = defaultDocBody(DocType.LETTER) },
                        modifier = Modifier.weight(1f)
                    ) { Text("Letter") }
                }
                Row(horizontalArrangement = Arrangement.spacedBy(8.dp), modifier = Modifier.fillMaxWidth()) {
                    OutlinedButton(
                        onClick = { docType = DocType.RESUME; body = defaultDocBody(DocType.RESUME) },
                        modifier = Modifier.weight(1f)
                    ) { Text("Resume") }
                    OutlinedButton(
                        onClick = { docType = DocType.CONTRACT; body = defaultDocBody(DocType.CONTRACT) },
                        modifier = Modifier.weight(1f)
                    ) { Text("Contract") }
                }
                Row(horizontalArrangement = Arrangement.spacedBy(8.dp), modifier = Modifier.fillMaxWidth()) {
                    OutlinedButton(
                        onClick = { docType = DocType.BANK_STATEMENT; body = defaultDocBody(DocType.BANK_STATEMENT) },
                        modifier = Modifier.weight(1f)
                    ) { Text("Bank Stmt") }
                    OutlinedButton(
                        onClick = { docType = DocType.DRIVERS_LICENSE; body = defaultDocBody(DocType.DRIVERS_LICENSE) },
                        modifier = Modifier.weight(1f)
                    ) { Text("Driver's") }
                    OutlinedButton(
                        onClick = { docType = DocType.PASSPORT; body = defaultDocBody(DocType.PASSPORT) },
                        modifier = Modifier.weight(1f)
                    ) { Text("Passport") }
                    OutlinedButton(
                        onClick = { docType = DocType.ID_CARD; body = defaultDocBody(DocType.ID_CARD) },
                        modifier = Modifier.weight(1f)
                    ) { Text("ID Card") }
                }
            }
            Card(label = "Title") {
                OutlinedTextField(value = title, onValueChange = { title = it }, modifier = Modifier.fillMaxWidth())
            }
            Card(label = "Body") {
                OutlinedTextField(
                    value = body,
                    onValueChange = { body = it },
                    modifier = Modifier.fillMaxWidth().heightIn(min = 160.dp),
                    label = { Text("Document body — type or paste content here") }
                )
            }
        }
        Row {
            FilledTonalButton(
                onClick = {
                    saving = true; saveResult = null
                    scope.launch {
                        val safe = sanitize(title.ifBlank { "crosseyes-doc" })
                        val ts = java.text.SimpleDateFormat("yyyyMMdd-HHmmss", java.util.Locale.US).format(Date())
                        val path = File(ctx.getDir("output", 0), "${ts}-${safe}.txt")
                        path.parentFile?.mkdirs()
                        val txt = buildString {
                            appendLine("CROSS EYES: ${docType.name}")
                            appendLine("Title: $title")
                            appendLine("Date: ${Date()}")
                            appendLine("---")
                            appendLine(body)
                        }
                        path.writeText(txt)
                        savedCount += 1; saveResult = path.absolutePath; saving = false
                    }
                },
                enabled = !saving,
                modifier = Modifier.fillMaxWidth()
            ) {
                Icon(Icons.Filled.Description, contentDescription = null, modifier = Modifier.size(18.dp))
                Spacer(Modifier.width(8.dp))
                Text(if (saving) "Working…" else "Generate & Save  ($savedCount)")
            }
        }
        saveResult?.let {
            StatusPill("Saved: $it", active = true)
        }
    }
}

private fun sanitize(s: String): String = s
    .replace(Regex("[^a-zA-Z0-9 ._-]"), "")
    .trim()
    .take(60).replace(' ', '_')
